import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { SEED_PRODUCTS } from '../src/database/seed/data/products.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'assets', 'seed-images');

const palette = ['#1f6feb', '#238636', '#9a6700', '#8250df', '#cf222e', '#0550ae'];

await mkdir(outDir, { recursive: true });

for (const [index, product] of SEED_PRODUCTS.entries()) {
  const color = palette[index % palette.length]!;
  const svg = `<svg width="800" height="800" xmlns="http://www.w3.org/2000/svg">
    <rect width="800" height="800" fill="${color}"/>
    <rect x="48" y="48" width="704" height="704" fill="none" stroke="#ffffff" stroke-width="8"/>
    <text x="400" y="380" fill="#ffffff" font-size="36" font-family="sans-serif" text-anchor="middle">${escapeXml(product.name)}</text>
    <text x="400" y="440" fill="#ffffff" font-size="22" font-family="sans-serif" text-anchor="middle">${product.sku}</text>
  </svg>`;
  const webp = await sharp(Buffer.from(svg)).webp({ quality: 80 }).toBuffer();
  await writeFile(join(outDir, `${product.slug}.webp`), webp);
}

await writeFile(
  join(outDir, 'CREDITS.md'),
  '# Seed image credits\n\nPlaceholder 800×800 WebP images generated by `scripts/generate-seed-images.ts`. No third-party photos.\n',
);

console.log(`Wrote ${SEED_PRODUCTS.length} placeholder images to assets/seed-images`);

function escapeXml(value: string): string {
  return value.replace(/[&<>"']/g, (char) => {
    if (char === '&') return '&amp;';
    if (char === '<') return '&lt;';
    if (char === '>') return '&gt;';
    if (char === '"') return '&quot;';
    return '&#39;';
  });
}
